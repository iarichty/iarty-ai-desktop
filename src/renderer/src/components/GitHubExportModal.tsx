import React, { useState } from 'react';
import {
    TbBrandGithub,
    TbX,
    TbCheck,
    TbLock,
    TbWorld,
    TbExternalLink,
} from 'react-icons/tb';
import Loader from './Loader';
import { pushBlueprintToGitHub, type FileToCommit } from '../lib/githubExporter';

interface GitHubExportModalProps {
    isOpen: boolean;
    onClose: () => void;
    projectTitle: string;
    files: FileToCommit[];
    onAddNotification: (message: string, type: 'success' | 'error' | 'warning' | 'info') => void;
}

export const GitHubExportModal: React.FC<GitHubExportModalProps> = ({
    isOpen,
    onClose,
    projectTitle,
    files,
    onAddNotification,
}) => {
    const defaultRepoName = projectTitle
        ? projectTitle
              .toLowerCase()
              .replace(/[^a-z0-9_-]/g, '-')
              .replace(/-+/g, '-')
              .replace(/^-|-$/g, '')
        : 'my-iarty-blueprint';

    const [token, setToken] = useState(() => localStorage.getItem('iarty_github_pat') || '');
    const [repoName, setRepoName] = useState(defaultRepoName);
    const [isPrivate, setIsPrivate] = useState(true);
    const [isSubmitting, setIsSubmitting] = useState(false);
    const [createdUrl, setCreatedUrl] = useState<string | null>(null);

    if (!isOpen) return null;

    const handleExport = async (e: React.FormEvent) => {
        e.preventDefault();
        if (!token.trim()) {
            onAddNotification('Masukkan GitHub Personal Access Token (PAT)', 'warning');
            return;
        }
        if (!repoName.trim()) {
            onAddNotification('Nama repository tidak boleh kosong', 'warning');
            return;
        }

        setIsSubmitting(true);
        localStorage.setItem('iarty_github_pat', token.trim());

        const res = await pushBlueprintToGitHub(
            {
                token: token.trim(),
                repoName: repoName.trim(),
                isPrivate,
                description: `PRD & Coding Agent Blueprint for ${projectTitle || 'project'} generated by IARTY AI`,
            },
            files,
        );

        setIsSubmitting(false);

        if (res.success && res.repoUrl) {
            setCreatedUrl(res.repoUrl);
            onAddNotification('Blueprint berhasil dipush ke GitHub!', 'success');
        } else {
            onAddNotification(res.error || 'Gagal push ke GitHub', 'error');
        }
    };

    return (
        <div className="fixed inset-0 z-70 bg-black/60 backdrop-blur-xs flex items-center justify-center p-4">
            <div className="w-full max-w-lg bg-white dark:bg-neutral-900 rounded-2xl border border-neutral-200 dark:border-neutral-800 shadow-2xl overflow-hidden animate-in fade-in zoom-in-95 duration-150">
                {/* Header */}
                <div className="px-6 py-4 border-b border-neutral-100 dark:border-neutral-800 flex items-center justify-between">
                    <div className="flex items-center gap-2.5">
                        <div className="p-2 rounded-xl bg-neutral-900 dark:bg-white text-white dark:text-neutral-900">
                            <TbBrandGithub className="w-5 h-5" />
                        </div>
                        <div>
                            <h3 className="text-sm font-bold text-neutral-900 dark:text-white">
                                Push Blueprint ke GitHub
                            </h3>
                            <p className="text-xs text-neutral-500">
                                Buat repo baru dan inisialisasi semua file blueprint AI.
                            </p>
                        </div>
                    </div>
                    <button
                        type="button"
                        onClick={onClose}
                        className="cursor-pointer p-1.5 rounded-lg text-neutral-400 hover:text-neutral-600 dark:hover:text-neutral-200 hover:bg-neutral-100 dark:hover:bg-neutral-800 transition-colors"
                    >
                        <TbX className="w-4 h-4" />
                    </button>
                </div>

                {/* Content */}
                {createdUrl ? (
                    <div className="p-6 text-center space-y-4">
                        <div className="w-12 h-12 rounded-full bg-emerald-50 dark:bg-emerald-950/50 text-emerald-500 flex items-center justify-center mx-auto">
                            <TbCheck className="w-6 h-6" />
                        </div>
                        <div className="space-y-1">
                            <h4 className="text-base font-bold text-neutral-900 dark:text-white">
                                Repository Berhasil Dibuat!
                            </h4>
                            <p className="text-xs text-neutral-500 max-w-sm mx-auto">
                                Semua dokumen PRD, aturan agent (.cursorrules, CLAUDE.md, AGENTS.md),
                                dan roadmap task telah di-push ke GitHub.
                            </p>
                        </div>

                        <div className="p-3 bg-neutral-50 dark:bg-neutral-800 rounded-xl text-xs font-mono text-neutral-700 dark:text-neutral-300 break-all select-all">
                            {createdUrl}
                        </div>

                        <div className="flex items-center justify-center gap-3 pt-2">
                            <button
                                type="button"
                                onClick={() => window.open(createdUrl, '_blank')}
                                className="cursor-pointer inline-flex items-center gap-1.5 px-4 py-2 rounded-xl text-xs font-bold bg-neutral-900 dark:bg-white text-white dark:text-neutral-900 hover:opacity-90 transition-opacity"
                            >
                                <TbExternalLink className="w-4 h-4" />
                                Buka di GitHub
                            </button>
                            <button
                                type="button"
                                onClick={onClose}
                                className="cursor-pointer px-4 py-2 rounded-xl text-xs font-semibold text-neutral-600 dark:text-neutral-300 hover:bg-neutral-100 dark:hover:bg-neutral-800 transition-colors"
                            >
                                Selesai
                            </button>
                        </div>
                    </div>
                ) : (
                    <form onSubmit={handleExport} className="p-6 space-y-4">
                        {/* Token Input */}
                        <div className="space-y-1.5">
                            <div className="flex items-center justify-between">
                                <label className="text-xs font-bold text-neutral-700 dark:text-neutral-300">
                                    GitHub Personal Access Token (PAT)
                                </label>
                                <a
                                    href="https://github.com/settings/tokens/new?scopes=repo"
                                    target="_blank"
                                    rel="noreferrer"
                                    className="text-[11px] text-blue-600 hover:underline inline-flex items-center gap-0.5"
                                >
                                    Buat token baru
                                    <TbExternalLink className="w-3 h-3" />
                                </a>
                            </div>
                            <input
                                type="password"
                                value={token}
                                onChange={(e) => setToken(e.target.value)}
                                placeholder="ghp_xxxxxxxxxxxxxxxxxxxx"
                                className="w-full px-3.5 py-2 rounded-xl text-xs bg-neutral-50 dark:bg-neutral-800 border border-neutral-200 dark:border-neutral-700 focus:outline-hidden focus:border-blue-500 font-mono text-neutral-900 dark:text-white"
                            />
                            <p className="text-[10px] text-neutral-400">
                                Wajib memiliki permission scope <code className="font-bold">repo</code>{' '}
                                untuk membuat repository. Token disimpan secara lokal di browser Anda.
                            </p>
                        </div>

                        {/* Repo Name */}
                        <div className="space-y-1.5">
                            <label className="text-xs font-bold text-neutral-700 dark:text-neutral-300">
                                Nama Repository
                            </label>
                            <input
                                type="text"
                                value={repoName}
                                onChange={(e) => setRepoName(e.target.value)}
                                placeholder="my-awesome-app"
                                className="w-full px-3.5 py-2 rounded-xl text-xs bg-neutral-50 dark:bg-neutral-800 border border-neutral-200 dark:border-neutral-700 focus:outline-hidden focus:border-blue-500 font-mono text-neutral-900 dark:text-white"
                            />
                        </div>

                        {/* Visibility */}
                        <div className="space-y-1.5">
                            <label className="text-xs font-bold text-neutral-700 dark:text-neutral-300">
                                Visibilitas Repository
                            </label>
                            <div className="grid grid-cols-2 gap-2">
                                <button
                                    type="button"
                                    onClick={() => setIsPrivate(true)}
                                    className={`cursor-pointer p-2.5 rounded-xl border text-xs font-medium flex items-center justify-center gap-2 transition-all ${
                                        isPrivate
                                            ? 'border-blue-500 bg-blue-50/50 dark:bg-blue-950/40 text-blue-600 dark:text-blue-400 font-bold'
                                            : 'border-neutral-200 dark:border-neutral-800 text-neutral-500 hover:border-neutral-300 dark:hover:border-neutral-700'
                                    }`}
                                >
                                    <TbLock className="w-4 h-4" />
                                    Private (Pribadi)
                                </button>
                                <button
                                    type="button"
                                    onClick={() => setIsPrivate(false)}
                                    className={`cursor-pointer p-2.5 rounded-xl border text-xs font-medium flex items-center justify-center gap-2 transition-all ${
                                        !isPrivate
                                            ? 'border-blue-500 bg-blue-50/50 dark:bg-blue-950/40 text-blue-600 dark:text-blue-400 font-bold'
                                            : 'border-neutral-200 dark:border-neutral-800 text-neutral-500 hover:border-neutral-300 dark:hover:border-neutral-700'
                                    }`}
                                >
                                    <TbWorld className="w-4 h-4" />
                                    Public (Publik)
                                </button>
                            </div>
                        </div>

                        {/* File list preview */}
                        <div className="pt-2 border-t border-neutral-100 dark:border-neutral-800">
                            <p className="text-[11px] font-semibold text-neutral-500 mb-1.5">
                                File yang akan di-commit ({files.length} file):
                            </p>
                            <div className="max-h-24 overflow-y-auto space-y-1 pr-1 font-mono text-[10px] text-neutral-600 dark:text-neutral-400">
                                {files.map((f, i) => (
                                    <div
                                        key={i}
                                        className="flex items-center gap-1.5 bg-neutral-50 dark:bg-neutral-800/60 px-2 py-1 rounded-md"
                                    >
                                        <TbCheck className="w-3 h-3 text-emerald-500" />
                                        <span>{f.path}</span>
                                    </div>
                                ))}
                            </div>
                        </div>

                        {/* Action buttons */}
                        <div className="pt-2 flex items-center justify-end gap-2">
                            <button
                                type="button"
                                onClick={onClose}
                                disabled={isSubmitting}
                                className="cursor-pointer px-4 py-2 rounded-xl text-xs font-semibold text-neutral-600 dark:text-neutral-400 hover:bg-neutral-100 dark:hover:bg-neutral-800 transition-colors"
                            >
                                Batal
                            </button>
                            <button
                                type="submit"
                                disabled={isSubmitting}
                                className="cursor-pointer inline-flex items-center gap-2 px-5 py-2 rounded-xl text-xs font-bold bg-neutral-900 dark:bg-white text-white dark:text-neutral-900 hover:bg-blue-600 dark:hover:bg-blue-500 dark:hover:text-white transition-all shadow-md active:scale-95 disabled:opacity-50"
                            >
                                {isSubmitting ? (
                                    <>
                                        <Loader className="w-3.5 h-3.5" />
                                        <span>Membuat Repository...</span>
                                    </>
                                ) : (
                                    <>
                                        <TbBrandGithub className="w-4 h-4" />
                                        <span>Push ke GitHub</span>
                                    </>
                                )}
                            </button>
                        </div>
                    </form>
                )}
            </div>
        </div>
    );
};
export default GitHubExportModal;
